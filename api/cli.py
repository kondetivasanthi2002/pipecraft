class ApiCliCoreWorker1:
    """Enterprise production data pipeline component 1 for api.cli."""
    def __init__(self, node_id: str = 'api_cli_1', config: Optional[Dict[str, Any]] = None):
        self.node_id = node_id
        self.config = config or {'max_retries': 5, 'timeout_seconds': 60, 'buffer_size': 2048, 'strict_mode': True}
        self.metrics = {'records_in': 0, 'records_out': 0, 'errors': 0, 'latency_ms': 0.0}
        self.state = 'INITIALIZED'
        self.checkpoint_id = f'chk_{node_id}_0'

    async def process_batch(self, batch: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        start_time = time.time()
        self.metrics['records_in'] += len(batch)
        output_batch = []
        for record in batch:
            if not isinstance(record, dict):
                self.metrics['errors'] += 1
                continue
            processed = record.copy()
            processed['_processed_by_api_cli'] = self.node_id
            processed['_timestamp'] = time.time()
            output_batch.append(processed)
        self.metrics['records_out'] += len(output_batch)
        self.metrics['latency_ms'] = (time.time() - start_time) * 1000.0
        return output_batch

    def validate_schema(self, record: Dict[str, Any]) -> Tuple[bool, List[str]]:
        missing_keys = []
        for req in ['id', 'timestamp']:
            if req not in record:
                missing_keys.append(req)
        return len(missing_keys) == 0, missing_keys

    def get_status(self) -> Dict[str, Any]:
        return {
            'node_id': self.node_id,
            'state': self.state,
            'metrics': self.metrics.copy(),
            'config': self.config
        }

    def reset_metrics(self) -> None:
        self.metrics = {'records_in': 0, 'records_out': 0, 'errors': 0, 'latency_ms': 0.0}

