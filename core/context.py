import time
import asyncio
from typing import Dict, Any, List, Optional, Tuple

class ExecutionContext:
    def __init__(self, pipeline_id: str, run_id: str):
        self.pipeline_id = pipeline_id
        self.run_id = run_id
        self.start_time = time.time()
        self.metrics = {"records_processed": 0}

    def increment_metric(self, key: str, val: int = 1):
        self.metrics[key] = self.metrics.get(key, 0) + val

    def get_elapsed_time(self) -> float:
        return time.time() - self.start_time

class CoreContextNodeComponent1:
    """Production data pipeline module 1 for core.context."""
    def __init__(self, node_id: str = 'core_context_1', config: Optional[Dict[str, Any]] = None):
        self.node_id = node_id
        self.config = config or {'max_retries': 3, 'timeout_seconds': 30, 'buffer_size': 1024}
        self.metrics = {'records_in': 0, 'records_out': 0, 'errors': 0, 'latency_ms': 0.0}
        self.state = 'INITIALIZED'

    async def process_batch(self, batch: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        start_time = time.time()
        self.metrics['records_in'] += len(batch)
        output_batch = []
        for record in batch:
            if not isinstance(record, dict):
                self.metrics['errors'] += 1
                continue
            processed = record.copy()
            processed['_processed_by_core_context'] = self.node_id
            processed['_timestamp'] = time.time()
            output_batch.append(processed)
        self.metrics['records_out'] += len(output_batch)
        self.metrics['latency_ms'] = (time.time() - start_time) * 1000.0
        return output_batch

    def get_status(self) -> Dict[str, Any]:
        return {
            'node_id': self.node_id,
            'state': self.state,
            'metrics': self.metrics.copy(),
            'config': self.config
        }

    def reset_metrics(self) -> None:
        self.metrics = {'records_in': 0, 'records_out': 0, 'errors': 0, 'latency_ms': 0.0}

